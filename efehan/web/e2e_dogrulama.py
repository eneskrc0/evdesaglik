"""Mesleki doğrulama akışının uçtan uca provası (headless Chrome).
Çalıştır:  python web/e2e_dogrulama.py <örnek dosya klasörü>
Klasörde: notlar.txt, buyuk.pdf (>10 MB), diploma_ornek.pdf, uzmanlik_ornek.png olmalı."""
import sys
from pathlib import Path
from playwright.sync_api import sync_playwright

PAGE = (Path(__file__).resolve().parent / "dist" / "kapida.html").as_uri()
D = Path(sys.argv[1] if len(sys.argv) > 1 else "/tmp/vt")
ok = 0


def check(cond, msg):
    global ok
    if not cond:
        raise AssertionError(msg)
    ok += 1
    print("  ✓", msg)


with sync_playwright() as pw:
    br = pw.chromium.launch(executable_path="/usr/bin/google-chrome", args=["--no-sandbox"])
    pg = br.new_page(viewport={"width": 1280, "height": 1000})
    errs = []
    pg.on("pageerror", lambda e: errs.append(str(e)))
    pg.goto(PAGE)
    h = pg.locator("#hScreen")
    txt = lambda: h.inner_text()

    print("1) İlk giriş")
    check("Mesleğini belirt" in txt(), "ilk girişte doğrulama ekranı açılıyor")
    check("Prototip: Belgeler resmî sistemlerden doğrulanmaz. Gerçek kişisel belge yüklemeyin." in txt(), "prototip uyarısı görünüyor")
    check(pg.locator("label[for=v-name]").inner_text() == "Ad soyad", "alanların görünür etiketi var")
    fs = pg.eval_on_selector(".v-p, .v-inp, .v-label", "e => parseFloat(getComputedStyle(e).fontSize)")
    hs = pg.eval_on_selector(".v-h", "e => parseFloat(getComputedStyle(e).fontSize)")
    bh = pg.eval_on_selector(".v-main", "e => e.getBoundingClientRect().height")
    check(fs >= 18 and 24 <= hs <= 28 and bh >= 48, f"boyutlar: metin {fs}px, başlık {hs}px, düğme {bh:.0f}px")
    check(not any(w in txt() for w in ["T.C.", "kimlik no", "selfie", "e-Devlet şifre"]), "T.C. no / selfie / e-Devlet şifresi istenmiyor")

    print("2) Zorunlu alanlar ve mesleğe göre alanlar")
    h.get_by_role("button", name="Devam et").click()
    t = txt()
    check("Ad soyadını yaz." in t and "Mesleğini seç." in t and "Çalıştığın kuruluşu" in t, "boş adım 1'de alan yanında hatalar")
    check(pg.locator("#v-name").get_attribute("aria-invalid") == "true", "hatalı alan işaretli (aria-invalid)")
    pg.fill("#v-name", "Deneme Kullanıcı")
    check(pg.locator("#v-name-err").count() == 0, "yazınca hata kalkıyor")
    check(pg.locator("[data-vr=hekimType]").count() == 0, "hekim seçilmeden pratisyen/uzman sorusu yok")
    h.get_by_text("Hekim", exact=True).click()
    check(pg.locator("[data-vr=hekimType]").count() == 2, "Hekim → Pratisyen/Uzman seçimi açılıyor")
    check(pg.locator("#v-specialty").count() == 0, "pratisyen/uzman seçilmeden uzmanlık alanı yok")
    h.get_by_text("Uzman hekim", exact=True).click()
    check(pg.locator("#v-specialty").count() == 1, "Uzman → uzmanlık alanı soruluyor")
    pg.fill("#v-org", "Örnek Aile Sağlığı Merkezi")
    h.get_by_role("button", name="Devam et").click()
    check("Uzmanlık alanını yaz." in txt(), "uzmanlık alanı boşsa hata")
    pg.fill("#v-specialty", "İç hastalıkları")
    h.get_by_role("button", name="Devam et").click()
    check("Belgelerini ekle" in txt() and "Belgelerin, mesleki başvurunun incelenmesi için alınır." in txt(), "adım 2 açıldı, kısa açıklama var")
    check("Uzmanlık belgesi" in txt(), "uzman hekimde uzmanlık belgesi alanı var")

    print("3) Dosya kontrolleri")
    h.get_by_role("button", name="Başvuruyu gözden geçir").click()
    t = txt()
    check("Diploma ya da mezuniyet belgeni ekle." in t and "Uzmanlık belgeni ekle." in t, "zorunlu belgeler olmadan ilerlenmiyor")
    pg.set_input_files("#v-file-diploma", str(D / "notlar.txt"))
    check("dosya türü kabul edilmiyor" in txt(), ".txt reddediliyor")
    pg.set_input_files("#v-file-diploma", str(D / "buyuk.pdf"))
    check("Dosya çok büyük" in txt() and "En fazla 10 MB" in txt(), "10 MB üstü reddediliyor")
    pg.set_input_files("#v-file-diploma", str(D / "diploma_ornek.pdf"))
    t = txt()
    check("diploma_ornek.pdf" in t and "Eklendi, henüz incelenmedi" in t, "dosya adı görünüyor, 'doğrulandı' denmiyor")
    check("doğrulandı" not in t.lower(), "ekranda 'doğrulandı' ifadesi yok")
    check(h.get_by_text("Değiştir").count() == 1 and h.get_by_role("button", name="Kaldır").count() == 1, "değiştir / kaldır seçenekleri var")
    h.get_by_role("button", name="Kaldır").click()
    check("diploma_ornek.pdf" not in txt(), "kaldır çalışıyor")
    pg.set_input_files("#v-file-diploma", str(D / "diploma_ornek.pdf"))
    pg.set_input_files("#v-file-uzmanlik", str(D / "uzmanlik_ornek.png"))
    pg.fill("#v-tescil", "12/3456")

    print("4) İleri-geri geçişte veri korunuyor")
    h.get_by_role("button", name="← Geri").click()
    check(pg.input_value("#v-name") == "Deneme Kullanıcı" and pg.input_value("#v-specialty") == "İç hastalıkları", "adım 1 verileri korunuyor")
    h.get_by_text("Pratisyen hekim", exact=True).click()
    h.get_by_role("button", name="Devam et").click()
    check("Uzmanlık belgesi" not in txt(), "pratisyende uzmanlık belgesi alanı kalkıyor")
    check("diploma_ornek.pdf" in txt() and pg.input_value("#v-tescil") == "12/3456", "adım 2 dosya ve tescil no korunuyor")
    h.get_by_role("button", name="← Geri").click()
    h.get_by_text("Uzman hekim", exact=True).click()
    check(pg.input_value("#v-specialty") == "İç hastalıkları", "uzmana dönünce uzmanlık alanı hâlâ dolu")
    h.get_by_role("button", name="Devam et").click()
    check("uzmanlik_ornek.png" in txt(), "uzmanlık belgesi bellekte duruyor")
    h.get_by_role("button", name="Başvuruyu gözden geçir").click()

    print("5) Gözden geçir ve gönder")
    t = txt()
    check("Başvurunu gönder" in t and "Deneme Kullanıcı" in t and "Uzman hekim · İç hastalıkları" in t and "diploma_ornek.pdf" in t and "uzmanlik_ornek.png" in t, "özet bilgileri ve belge adlarını gösteriyor")
    h.get_by_role("button", name="İncelemeye gönder").click()
    check("beyan kutusunu işaretle" in txt(), "beyan kutusu işaretlenmeden gönderilmiyor")
    h.get_by_role("button", name="Bilgileri düzenle").click()
    check("Mesleğini belirt" in txt() and pg.input_value("#v-org") == "Örnek Aile Sağlığı Merkezi", "bilgileri düzenle adım 1'e dönüyor, veri korunuyor")
    h.get_by_role("button", name="Devam et").click(); h.get_by_role("button", name="Başvuruyu gözden geçir").click()
    pg.check("#v-decl")
    h.get_by_role("button", name="İncelemeye gönder").click()
    t = txt()
    check("Başvurun alındı" in t and "İnceleme bekliyor" in t and "görev kabul etme durumun güncellenecek" in t, "gönderildi ekranı")
    h.get_by_role("button", name="Başvuru özetini gör").click()
    check("diploma_ornek.pdf" in txt(), "başvuru özeti görüntülenebiliyor")
    check(pg.evaluate("localStorage.length") == 0 and pg.evaluate("sessionStorage.length") == 0, "localStorage / sessionStorage boş")

    print("6) Görev kabul kilidi")
    h.get_by_role("button", name="Panele git").click()
    check("Görev kabul etme kapalı" in txt() and "başvuru: İnceleme bekliyor" in txt(), "panelde kilit bandı ve durum")
    h.locator("[data-open]").first.click()
    check(h.get_by_role("button", name="Kabul et").first.is_disabled(), "bekliyorken Kabul et kapalı")
    check("Başvurun onaylanınca görev kabul edebilirsin." in txt(), "neden kapalı olduğu yazıyor")
    h.get_by_role("button", name="Talepler").click()

    print("7) Demo durumları")
    ctl = pg.locator("#demoCtl")
    check("Demo kontrolleri" in ctl.inner_text(), "demo kontrolleri ayrı ve etiketli")
    ctl.get_by_role("button", name="Eksik belge").click()
    t = txt()
    check("Bir belge eksik" in t and "Gerekçe (örnek)" in t, "eksik belge: örnek gerekçe")
    h.get_by_role("button", name="Belgeyi tamamla").click()
    check("Belgelerini ekle" in txt() and "diploma_ornek.pdf" in txt(), "belgeyi tamamla → adım 2, belgeler duruyor")
    h.get_by_role("button", name="Panele dön").click()
    h.locator("[data-open]").first.click()
    check(h.get_by_role("button", name="Kabul et").first.is_disabled(), "eksik belgede Kabul et kapalı")
    h.get_by_role("button", name="Talepler").click()
    ctl.get_by_role("button", name="Uygun bulunmadı — demo").click()
    check("uygun bulunmadı" in txt().lower() and "Gerekçe (örnek)" in txt(), "uygun bulunmadı: kısa gerekçe")
    h.get_by_role("button", name="Yeniden inceleme iste").click()
    check("Başvurun inceleniyor" in txt() and "İnceleme bekliyor" in txt(), "yeniden inceleme → inceleme bekliyor")
    ctl.get_by_role("button", name="İnceleme bekliyor").click()
    check("Başvurun inceleniyor" in txt(), "demo: inceleme bekliyor")
    ctl.get_by_role("button", name="Onaylandı — demo").click()
    t = txt()
    check("Onaylandı — demo" in t and "gerçek mesleki yetkilendirme değildir" in t, "demo onayı gerçek yetki gibi sunulmuyor")
    h.get_by_role("button", name="Panele git").click()
    check("Görev kabul etme kapalı" not in txt(), "onayda kilit bandı kalkıyor")
    h.locator("[data-open]").first.click()
    btn = h.get_by_role("button", name="Kabul et").first
    check(btn.is_enabled(), "demo onayında Kabul et açılıyor")
    btn.click()
    check("rotana eklendi" in txt(), "kabul çalışıyor")

    print("8) Diğer meslekler")
    ctl.get_by_role("button", name="Baştan başlat").click()
    check(pg.input_value("#v-name") == "", "baştan başlat formu temizliyor")
    pg.fill("#v-name", "Örnek Hemşire"); h.get_by_text("Hemşire", exact=True).click(); pg.fill("#v-org", "Örnek Hastanesi")
    check(pg.locator("[data-vr=hekimType]").count() == 0, "hemşirede hekim türü sorulmuyor")
    h.get_by_role("button", name="Devam et").click()
    check("Uzmanlık belgesi" not in txt() and "Diploma / mezuniyet belgesi" in txt(), "hemşirede yalnız diploma zorunlu")
    h.get_by_role("button", name="← Geri").click()
    h.get_by_text("Diğer", exact=True).click()
    h.get_by_role("button", name="Devam et").click()
    check("Mesleğinin adını yaz." in txt(), "Diğer seçilince meslek adı zorunlu")

    print("9) Hasta tarafı bozulmadı")
    ctl.get_by_role("button", name="Onaylandı — demo").click()
    h.get_by_role("button", name="Panele git").click()
    p = pg.locator("#pScreen")
    p.locator("[data-tile]").first.click()
    for _ in range(4):
        pg.wait_for_selector("#pScreen [data-quick]", timeout=5000)
        p.locator("[data-quick]").first.click()
    pg.wait_for_selector("#pScreen [data-act=options]", timeout=5000)
    p.locator("[data-act=options]").click()
    pg.evaluate("document.querySelectorAll('details.klasik').forEach(d => d.open = true)"); p.locator("details.klasik [data-pick]").first.click()
    p.locator("[data-act=confirm]").click()
    check("Talebin gönderildi" in p.inner_text(), "hasta randevu talebi gönderebiliyor")
    acc = h.locator("[data-act=haccept]")
    check(acc.count() == 1 and acc.is_enabled(), "talep sağlık çalışanında açılıyor, onaylıyken kabul edilebilir")
    acc.click()
    check("Randevun kesinleşti" in p.inner_text(), "kabul hastaya yansıyor")

    print("10) Mobil genişlik")
    m = br.new_page(viewport={"width": 390, "height": 844})
    m.goto(PAGE)
    m.locator(".switch button[data-show=h]").click()
    over = m.evaluate("document.documentElement.scrollWidth > window.innerWidth + 1")
    check(not over and m.locator("#hScreen .v-h").is_visible(), "390 px'te taşma yok, form görünüyor")
    m.screenshot(path=str(Path(__file__).resolve().parent / "dist" / "dogrulama_mobil.png"), full_page=False)
    check(not errs, f"sayfa hatası yok {errs}")
    br.close()
print(f"\nTamam: {ok} kontrol geçti.")
